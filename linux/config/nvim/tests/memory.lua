local config = vim.fn.fnamemodify(debug.getinfo(1, "S").source:sub(2), ":p:h:h")
vim.opt.rtp:prepend(config)
local memory = require("core.memory")
local original = vim.api.nvim_get_current_buf()
local ok, err = xpcall(function()
  memory.open()
  local buf = vim.api.nvim_get_current_buf()
  assert(buf ~= original and vim.bo[buf].buftype == "nofile")
  assert(vim.wait(10000, function()
    local line = vim.api.nvim_buf_get_lines(buf, 0, 1, false)[1]
    return line and line:find("Neovim memory", 1, true) ~= nil
  end, 10), "asynchronous snapshot did not render")
  local lines = table.concat(vim.api.nvim_buf_get_lines(buf, 0, -1, false), "\n")
  assert(lines:find(tostring(vim.fn.getpid()), 1, true), "editor missing from process tree")
  assert(lines:find("TOTAL", 1, true), "total missing")
  assert(not vim.bo[buf].modifiable, "diagnostics buffer is editable")
  memory.open()
  assert(vim.api.nvim_get_current_buf() == buf, "command created duplicate report")
  -- Close immediately during refresh; a late callback must not recreate the view.
  vim.cmd("close")
  assert(vim.api.nvim_get_current_buf() == original)
  memory.open()
  local replacement = vim.api.nvim_get_current_buf()
  assert(replacement ~= buf)
  assert(vim.wait(10000, function()
    return vim.api.nvim_buf_get_lines(replacement, 0, 1, false)[1]:find("Neovim memory", 1, true)
  end, 10))
  vim.cmd("close")
end, debug.traceback)
if not ok then io.stderr:write(err .. "\n"); os.exit(1) end
print("PASS: asynchronous memory report, process tree, reuse, refresh cancellation, reopen")
